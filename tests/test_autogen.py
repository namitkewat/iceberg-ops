def _wrap_in_class(upgrade_body: str, downgrade_body: str) -> str:
    """Wrap rendered method bodies into a minimal class so we can ``compile()``.

    The renderer emits 8-space-indented body lines (two indent levels:
    ``class`` -> ``def``). Build the harness around them by
    concatenation rather than ``textwrap.dedent``, which would
    mishandle the empty blank line inside the body block.
    """
    return (
        "from __future__ import annotations\n"
        "from pyiceberg import types as ice_types\n"
        "from pyiceberg import transforms\n"
        "from iceberg_ops.migration import BaseMigration, MigrationContext\n"
        "\n"
        "class Migration(BaseMigration):\n"
        '    version = "0001"\n'
        '    description = "test"\n'
        "    def upgrade(self, ctx: MigrationContext) -> None:\n" + upgrade_body + "\n"
        "    def downgrade(self, ctx: MigrationContext) -> None:\n" + downgrade_body + "\n"
    )


def _compiles(source: str) -> bool:
    """Return True iff *source* parses as valid Python."""
    try:
        compile(source, "<autogen>", "exec")
    except SyntaxError:
        return False
    return True


def _exec_source(source: str) -> dict[str, Any]:
    """Execute generated module *source* and return its namespace."""
    namespace: dict[str, Any] = {"__name__": "_autogen_generated"}
    exec(compile(source, "<autogen>", "exec"), namespace)
    return namespace


