def _users_with(*, drop: tuple[str, ...] = (), extra: tuple[pa.Field, ...] = (), **types: Any):
    """``_USERS`` minus *drop*, with retyped / renamed fields, plus *extra*."""
    fields = []
    for f in _USERS:
        if f.name in drop:
            continue
        fields.append(types.get(f.name, f))
    return pa.schema([*fields, *extra])


_EMAIL = pa.field("email", pa.string())

_ROLLBACK_CASES = {
    "add_only": (_users_with(extra=(_EMAIL,)), None, True),
    "rename_with_hint": (
        _users_with(name=pa.field("full_name", pa.string())),
        {"name": "full_name"},
        True,
    ),
    "add_and_delete": (_users_with(drop=("note",), extra=(_EMAIL,)), None, False),
    "int_to_long": (_users_with(score=pa.field("score", pa.int64())), None, False),
    "add_and_int_to_long": (
        _users_with(score=pa.field("score", pa.int64()), extra=(_EMAIL,)),
        None,
        False,
    ),
}


class TestGenerateMigrateRollback:
    @pytest.mark.parametrize("case", list(_ROLLBACK_CASES))
    def test_generate_migrate_rollback(self, case: str, memory_catalog, tmp_path: Path) -> None:
        from iceberg_ops.history import MigrationHistory

        target, hints, reversible = _ROLLBACK_CASES[case]
        memory_catalog.create_namespace("ns")
        memory_catalog.create_table("ns.users", schema=_USERS)
        original = memory_catalog.load_table("ns.users").schema()

        ops = schema_diff_to_ops(current=original, target=target, rename_hints=hints)
        d = _migrations_dir(tmp_path)
        write_autogenerated_revision(
            version="0001",
            description=case,
            ops=ops,
            target_table="users",
            out_path=d / "0001_autogen.py",
        )
        runner = MigrationRunner(memory_catalog, namespace="ns", migrations_dir=str(d))
        runner.migrate()

        upgraded = memory_catalog.load_table("ns.users").schema()
        assert schema_diff_to_ops(current=upgraded, target=target) == []

        if reversible:
            runner.rollback()
            restored = memory_catalog.load_table("ns.users").schema()
            assert [(f.name, f.field_type) for f in restored.fields] == [
                (f.name, f.field_type) for f in original.fields
            ]
            return

        with pytest.raises(NotImplementedError, match="no step has been applied"):
            runner.rollback()
        after = memory_catalog.load_table("ns.users").schema()
        assert after.fields == upgraded.fields
        assert "0001" in MigrationHistory(memory_catalog).get_applied_versions("ns")
        # A second attempt fails the same way instead of on a missing field.
        with pytest.raises(NotImplementedError):
            runner.rollback()
        assert memory_catalog.load_table("ns.users").schema().fields == upgraded.fields
        if "int_to_long" in case:
            assert isinstance(after.find_field("score").field_type, ice_types.LongType)
        if "add" in case:
            assert after.find_field("email").name == "email"


