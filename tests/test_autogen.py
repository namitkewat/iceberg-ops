def _write_yaml(tmp_path: Path, text: str, *, bom: bool = False) -> str:
    path = tmp_path / "contract.yaml"
    path.write_bytes((b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8"))
    return str(path)


