    def test_no_helper_boilerplate_emitted(self):
        """The renderer uses direct ctx.<method> calls, not a helper variable.

        MigrationContext exposes enforce_column / enforce_rename
        / delete_column / add_column directly, so the autogen output
        should not include a 'helper = ctx.get_helper(...)' line.
        """
        ops = [
            MigrationOp(
                kind="add_column",
                args={"name": "email", "iceberg_type": ice_types.StringType()},
            ),
            MigrationOp(
                kind="set_property",
                args={"key": "x", "value": "1", "old_value": None},
            ),
        ]
        up, down = render_migration_body(ops, target_table="ns.t")
        assert "ctx.get_helper" not in up
        assert "ctx.get_helper" not in down
        assert "helper =" not in up
        assert "helper =" not in down

    def test_downgrade_body_reverses_op_order(self):
        ops = [
            MigrationOp(
                kind="add_column",
                args={"name": "a", "iceberg_type": ice_types.LongType()},
            ),
            MigrationOp(
                kind="add_column",
                args={"name": "b", "iceberg_type": ice_types.StringType()},
            ),
        ]
        _, down = render_migration_body(ops, target_table="ns.t")
        # Downgrade should delete b before a (reverse of upgrade).
        idx_b = down.index("'b'")
        idx_a = down.index("'a'")
        assert idx_b < idx_a


