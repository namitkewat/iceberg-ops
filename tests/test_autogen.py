def _migrations_dir(tmp_path: Path) -> Path:
    d = tmp_path / "migrations"
    d.mkdir()
    (d / "__init__.py").write_text("")
    return d


def _method_body(source: str, method: str) -> list[ast.stmt]:
    """Statements of ``Migration.<method>`` in generated *source*."""
    tree = ast.parse(source)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Migration")
    fn = next(n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == method)
    return fn.body


def _stmt_kinds(source: str, method: str) -> list[str]:
    return [type(s).__name__ for s in _method_body(source, method)]


def _ctx_calls(nodes: list[ast.stmt]) -> list[ast.Call]:
    """Every ``ctx.<method>(...)`` call inside *nodes*."""
    calls: list[ast.Call] = []
    for node in nodes:
        for sub in ast.walk(node):
            if (
                isinstance(sub, ast.Call)
                and isinstance(sub.func, ast.Attribute)
                and isinstance(sub.func.value, ast.Name)
                and sub.func.value.id == "ctx"
            ):
                calls.append(sub)
    return calls


def _str_constants(calls: list[ast.Call]) -> set[str]:
    """String literals passed (directly or inside containers) to *calls*."""
    found: set[str] = set()
    for call in calls:
        for arg in [*call.args, *(kw.value for kw in call.keywords)]:
            for sub in ast.walk(arg):
                if isinstance(sub, ast.Constant) and isinstance(sub.value, str):
                    found.add(ast.literal_eval(sub))
    return found


def _print_calls(source: str) -> list[ast.Call]:
    return [
        n
        for n in ast.walk(ast.parse(source))
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id == "print"
    ]


def _add(name: str, ice_type: ice_types.IcebergType, doc: str | None = None) -> MigrationOp:
    return MigrationOp(
        kind="add_column", args={"name": name, "iceberg_type": ice_type, "doc": doc}
    )


