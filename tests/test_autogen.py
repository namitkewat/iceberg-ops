class TestRoundTrip:
    def test_round_trip_add_column_via_runner(self, memory_catalog, tmp_path):
        """Real end-to-end: build a table, render an autogen migration,
        run it via :class:`MigrationRunner`, then verify the table now
        matches the target schema (empty diff)."""
        from iceberg_ops.core.schema import diff_schemas

        # Existing table with two columns.
        memory_catalog.create_namespace_if_not_exists("ns")
        memory_catalog.create_table(
            "ns.users",
            schema=pa.schema(
                [
                    pa.field("id", pa.int64(), nullable=False),
                    pa.field("name", pa.string()),
                ]
            ),
        )
        tbl = memory_catalog.load_table("ns.users")

        # Target adds `email`.
        target = pa.schema(
            [
                pa.field("id", pa.int64(), nullable=False),
                pa.field("name", pa.string()),
                pa.field("email", pa.string()),
            ]
        )

        ops = schema_diff_to_ops(current=tbl.schema(), target=target)
        assert len(ops) == 1 and ops[0].kind == "add_column"

        migrations_dir = tmp_path / "migrations"
        migrations_dir.mkdir()
        # Empty __init__ so importlib doesn't choke.
        (migrations_dir / "__init__.py").write_text("")

        write_autogenerated_revision(
            version="0001",
            description="add email",
            ops=ops,
            target_table="users",
            out_path=migrations_dir / "0001_add_email.py",
        )

        runner = MigrationRunner(
            memory_catalog,
            namespace="ns",
            migrations_dir=str(migrations_dir),
        )
        runner.migrate()

        tbl2 = memory_catalog.load_table("ns.users")
        # Re-diff: the autogen migration should have closed the gap.
        from iceberg_ops.autogen import _normalise_target

        target_aligned = _normalise_target(target, tbl2.schema(), {})
        diff = diff_schemas(tbl2.schema(), target_aligned)
        assert not diff.added
        assert not diff.removed
        assert not diff.changed


