class TestRenderMigrationFile:
    def test_full_file_compiles(self):
        ops = [
            MigrationOp(
                kind="add_column",
                args={"name": "email", "iceberg_type": ice_types.StringType()},
            ),
            MigrationOp(
                kind="rename_column",
                args={"old_name": "name", "new_name": "full_name"},
            ),
        ]
        source = render_migration_file(
            version="0007",
            description="add email and rename name",
            ops=ops,
            target_table="ns.users",
        )
        assert _compiles(source)
        module = _exec_source(source)
        assert module["Migration"].version == "0007"
        assert module["Migration"].description == "add email and rename name"

