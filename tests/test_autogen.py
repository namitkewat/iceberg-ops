class TestSchemaDiffToOps:
    def test_no_diff_returns_empty(self):
        cur = _current_schema()
        target = cur  # same instance, same IDs
        assert schema_diff_to_ops(current=cur, target=target) == []

    def test_add_column_op(self):
        cur = _current_schema()
        target = pa.schema(
            [
                pa.field("id", pa.int64(), nullable=False),
                pa.field("name", pa.string()),
                pa.field("score", pa.int32()),
                pa.field("email", pa.string()),
            ]
        )
        ops = schema_diff_to_ops(current=cur, target=target)
        kinds = [op.kind for op in ops]
        assert "add_column" in kinds
        add_op = next(op for op in ops if op.kind == "add_column")
        assert add_op.args["name"] == "email"
        assert isinstance(add_op.args["iceberg_type"], ice_types.StringType)

    def test_delete_column_op(self):
        cur = _current_schema()
        target = pa.schema(
            [
                pa.field("id", pa.int64(), nullable=False),
                pa.field("name", pa.string()),
                # score dropped
            ]
        )
        ops = schema_diff_to_ops(current=cur, target=target)
        delete_ops = [op for op in ops if op.kind == "delete_column"]
        assert len(delete_ops) == 1
        assert delete_ops[0].args["name"] == "score"

    def test_rename_column_op_with_hint(self):
        cur = _current_schema()
        target = pa.schema(
            [
                pa.field("id", pa.int64(), nullable=False),
                pa.field("full_name", pa.string()),  # was "name"
                pa.field("score", pa.int32()),
            ]
        )
        ops = schema_diff_to_ops(current=cur, target=target, rename_hints={"name": "full_name"})
        kinds = [op.kind for op in ops]
        # Exactly one rename, no add+delete pair.
        assert kinds.count("rename_column") == 1
        assert "add_column" not in kinds
        assert "delete_column" not in kinds
        rename_op = next(op for op in ops if op.kind == "rename_column")
        assert rename_op.args == {"old_name": "name", "new_name": "full_name"}

    def test_rename_without_hint_emits_drop_and_add(self):
        cur = _current_schema()
        target = pa.schema(
            [
                pa.field("id", pa.int64(), nullable=False),
                pa.field("full_name", pa.string()),  # was "name", no hint
                pa.field("score", pa.int32()),
            ]
        )
        ops = schema_diff_to_ops(current=cur, target=target)
        kinds = [op.kind for op in ops]
        # No rename without a hint.
        assert "rename_column" not in kinds
        assert "delete_column" in kinds
        assert "add_column" in kinds

    def test_type_promotion_emits_type_change(self):
        """int -> long is the canonical Iceberg type promotion."""
        cur = _current_schema()
        target = pa.schema(
            [
                pa.field("id", pa.int64(), nullable=False),
                pa.field("name", pa.string()),
                pa.field("score", pa.int64()),  # int -> long
            ]
        )
        ops = schema_diff_to_ops(current=cur, target=target)
        type_ops = [op for op in ops if op.kind == "type_change"]
        assert len(type_ops) == 1
        op = type_ops[0]
        assert op.args["name"] == "score"
        assert isinstance(op.args["old_iceberg_type"], ice_types.IntegerType)
        assert isinstance(op.args["new_iceberg_type"], ice_types.LongType)

    def test_combined_rename_and_type_change(self):
        cur = _current_schema()
        target = pa.schema(
            [
                pa.field("id", pa.int64(), nullable=False),
                pa.field("name", pa.string()),
                pa.field("rating", pa.int64()),  # was "score: int", now "rating: long"
            ]
        )
        ops = schema_diff_to_ops(current=cur, target=target, rename_hints={"score": "rating"})
        kinds = [op.kind for op in ops]
        # Both a rename op and a type_change op.
        assert "rename_column" in kinds
        assert "type_change" in kinds
        rename = next(op for op in ops if op.kind == "rename_column")
        assert rename.args == {"old_name": "score", "new_name": "rating"}
        type_change = next(op for op in ops if op.kind == "type_change")
        assert type_change.args["name"] == "rating"

    def test_schema_contract_as_target(self):
        cur = _current_schema()
        contract = SchemaContract(
            [
                ColumnSpec("id", ice_types.LongType(), required=True),
                ColumnSpec("name", ice_types.StringType()),
                ColumnSpec("score", ice_types.IntegerType()),
                ColumnSpec("email", ice_types.StringType()),
            ]
        )
        ops = schema_diff_to_ops(current=cur, target=contract)
        add_ops = [op for op in ops if op.kind == "add_column"]
        assert len(add_ops) == 1
        assert add_ops[0].args["name"] == "email"

    def test_iceberg_schema_target_passes_through(self):
        cur = _current_schema()
        target = IcebergSchema(
            *list(cur.fields),
            ice_types.NestedField(99, "extra", ice_types.DoubleType(), required=False),
        )
        ops = schema_diff_to_ops(current=cur, target=target)
        kinds = [op.kind for op in ops]
        assert kinds == ["add_column"]
        assert ops[0].args["name"] == "extra"

    def test_unsupported_target_type_raises(self):
        cur = _current_schema()
        with pytest.raises(TypeError, match=r"pa\.Schema, IcebergSchema, or SchemaContract"):
            schema_diff_to_ops(current=cur, target="not-a-schema")  # type: ignore[arg-type]


