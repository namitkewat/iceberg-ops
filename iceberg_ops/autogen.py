_AUTOGEN_TEMPLATE = '''\
"""
Migration $version - $doc_description.

.. warning::

   This migration was autogenerated by iceberg-ops from a schema diff.
   **Review every line before running** - autogenerate is a starting
   point, not a finished implementation. In particular:

   * Each step commits on its own, so a step that fails leaves the
     earlier steps applied.
   * Steps known not to run (incompatible or nested type changes,
     dropping a column the partition spec, sort order or identifier
     fields reference) and steps that cannot be reversed (column drops,
     type widening, partition-field removal, sort-order replacement,
     property removal with an unknown old value) make the method raise
     ``NotImplementedError`` before any step runs; the generated calls
     are kept as comments for manual completion.
   * upgrade() is idempotent and adopts columns that already exist;
     downgrade() still removes every column this migration lists, even
     in a namespace whose table already had it. Review downgrade()
     before rolling back a namespace whose table differed from the one
     that was diffed.
   * Nullability and doc changes on existing columns are not emitted.
   * Renames are emitted only for explicit rename hints
     (``--rename-hint old:new``); otherwise a rename appears as a drop
     plus an add.
"""

from __future__ import annotations
$imports
from iceberg_ops.migration import BaseMigration, MigrationContext


class Migration(BaseMigration):
    version = $version_literal
    description = $description_literal

    def upgrade(self, ctx: MigrationContext) -> None:
$upgrade_body

    def downgrade(self, ctx: MigrationContext) -> None:
$downgrade_body
'''


def render_migration_file(
    *,
    version: str,
    description: str,
    ops: list[MigrationOp],
    target_table: str,
) -> str:
    """
    Render a complete migration source file from autogen ops.

    Combines :func:`render_migration_body` with the autogen-specific
    docstring (which carries the "Review every line before running"
    warning) and the imports the ops need.

    Parameters
    ----------
    version : str
        Four-digit version, e.g. ``"0007"``.
    description : str
        Free-text description (e.g. the ``-m`` message). Stored verbatim
        as the ``description`` class attribute; a whitespace-collapsed
        copy goes into the module docstring.
    ops : list[MigrationOp]
        Ops to render.
    target_table : str
        Table identifier for the generated calls; see
        :func:`render_migration_body` (prefer a bare name).

    Returns
    -------
    str
        Full Python source ready to write to disk.

    Raises
    ------
    ValueError
        If ``version`` is not four digits or an op has an unknown kind.
    """
    if not re.fullmatch(r"\d{4}", version):
        raise ValueError(f"version must be four digits, e.g. '0007' (got {version!r}).")
    upgrade_body, downgrade_body = render_migration_body(ops, target_table=target_table)

    imports: list[str] = []
    if any(op.kind in {"add_column", "type_change"} for op in ops):
        imports.append("from pyiceberg import types as ice_types")
    if any(op.kind == "add_partition_field" for op in ops):
        imports.append("from pyiceberg import transforms")
    imports_block = "\n".join(imports) + "\n" if imports else ""

    return Template(_AUTOGEN_TEMPLATE).substitute(
        version=version,
        doc_description=_docstring_text(description),
        version_literal=repr(version),
        description_literal=repr(description),
        imports=imports_block,
        upgrade_body=upgrade_body,
        downgrade_body=downgrade_body,
    )


def write_autogenerated_revision(
    *,
    version: str,
    description: str,
    ops: list[MigrationOp],
    target_table: str,
    out_path: str | Path,
    overwrite: bool = False,
) -> str:
    """
    Render and write an autogenerated migration to *out_path*.

    The file is written as UTF-8 with LF line endings on every platform.

    Parameters
    ----------
    version : str
        Four-digit version, e.g. ``"0007"``.
    description : str
        Free-text description of the migration.
    ops : list[MigrationOp]
        Ops to render.
    target_table : str
        Table identifier for the generated calls; prefer a bare name so
        the migration follows the namespace it runs against.
    out_path : str or pathlib.Path
        Destination file.
    overwrite : bool, optional
        Replace an existing file at *out_path*. Default ``False``.

    Returns
    -------
    str
        The absolute path of the written file (string for symmetry
        with :func:`iceberg_ops.scaffolding.create_revision`).

    Raises
    ------
    FileExistsError
        If *out_path* exists and ``overwrite`` is false.
    ValueError
        If ``version`` is not four digits or an op has an unknown kind.
    """
    body = render_migration_file(
        version=version,
        description=description,
        ops=ops,
        target_table=target_table,
    )
    path = Path(out_path)
    if overwrite:
        path.write_text(body, encoding="utf-8", newline="\n")
        return str(path.resolve())
    # Exclusive create: a file created concurrently (another revision
    # run picking the same version) is never overwritten.
    try:
        with open(path, "x", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
    except FileExistsError:
        raise FileExistsError(
            f"{path} already exists; pass overwrite=True to replace it (hand edits are lost)."
        ) from None
    return str(path.resolve())


