def _transform_to_source(transform: Any) -> str:
    """Render a partition transform as Python source.

    Every PyIceberg transform has a constructor-style ``repr`` (for
    example ``BucketTransform(num_buckets=16)``); prefixing the
    ``transforms.`` module alias, which the file renderer imports, makes
    it a valid expression in the generated migration.
    """
    return f"transforms.{transform!r}"


def spec_diff_to_ops(
    *,
    current: PartitionSpec,
    target: PartitionSpec,
    schema: IcebergSchema,
) -> list[MigrationOp]:
    """
    Compute add / remove ops to evolve ``current`` partition spec into
    ``target``.

    Compares fields by their ``name`` (the spec-level partition name,
    not the source column). Each ``target`` field absent from
    ``current`` becomes an ``add_partition_field`` op; each ``current``
    field absent from ``target`` becomes a ``remove_partition_field``
    op.

    Parameters
    ----------
    current : PartitionSpec
        ``table.spec()`` from the existing table.
    target : PartitionSpec
        Desired spec.
    schema : IcebergSchema
        Used to resolve each partition field's source column name from
        its ``source_id`` so the generated migration can pass the
        correct argument to :meth:`MigrationContext.update_partition_spec`.
        A nested source is rendered as its full dotted path
        (``"addr.city"``).

    Returns
    -------
    list[MigrationOp]
        Ops in removal-first then add order.

    Raises
    ------
    ValueError
        If a partition field keeps its name but changes its source
        column or transform; autogenerate cannot evolve a field in
        place, so give the new field a different name in the target.
        Also if an added field's source id is not in *schema*.

    Op kinds emitted
    ----------------
    - ``remove_partition_field`` - args ``{"partition_name"}``
    - ``add_partition_field`` - args
      ``{"source_column", "transform_source", "partition_name"}``, where
      ``transform_source`` is Python source such as
      ``"transforms.DayTransform()"``.
    """
    current_by_name = {f.name: f for f in current.fields}
    target_by_name = {f.name: f for f in target.fields}

    for name, tf in target_by_name.items():
        cf = current_by_name.get(name)
        if cf is None or (cf.source_id, cf.transform) == (tf.source_id, tf.transform):
            continue
        if cf.transform != tf.transform:
            change = f"{cf.transform} -> {tf.transform}"
        else:
            old_src = schema.find_column_name(cf.source_id)
            new_src = schema.find_column_name(tf.source_id)
            change = f"source column {old_src!r} -> {new_src!r}"
        raise ValueError(
            f"partition field {name!r} changes {change}; autogenerate cannot evolve "
            "a field in place; rename it in the target spec."
        )

    ops: list[MigrationOp] = []
    for name in current_by_name:
        if name not in target_by_name:
            ops.append(
                MigrationOp(
                    kind="remove_partition_field",
                    args={"partition_name": name},
                )
            )
    for name, pf in target_by_name.items():
        if name not in current_by_name:
            source_col = schema.find_column_name(pf.source_id)
            if source_col is None:
                raise ValueError(
                    f"partition field {name!r}: source id {pf.source_id} is not in the schema."
                )
            ops.append(
                MigrationOp(
                    kind="add_partition_field",
                    args={
                        "source_column": source_col,
                        "transform_source": _transform_to_source(pf.transform),
                        "partition_name": name,
                    },
                )
            )
    return ops


def sort_order_diff_to_ops(
    *,
    current: SortOrder,
    target: SortOrder,
    schema: IcebergSchema,
) -> list[MigrationOp]:
    """
    Emit a single ``set_sort_order`` op when the orders differ.

    The renderer translates this to
    ``ctx.replace_sort_order(target_table, sort_fields=[(col, dir),
    ...])`` - replacing the entire sort order rather than adding /
    removing fields, which matches PyIceberg's
    ``replace_sort_order`` semantics.

    Two orders are considered identical iff they have the same number
    of fields, in the same order, with the same ``source_id``,
    ``transform``, ``direction`` and ``null_order``.

    Parameters
    ----------
    current : SortOrder
        ``table.sort_order()`` from the existing table.
    target : SortOrder
        Desired sort order.
    schema : IcebergSchema
        Used to resolve each sort field's source column name; a nested
        source is rendered as its full dotted path (``"addr.city"``).

    Returns
    -------
    list[MigrationOp]
        ``[]`` when the orders are identical, otherwise one
        ``set_sort_order`` op with args ``{"sort_fields": [(column,
        "asc" | "desc"), ...]}``.

    Raises
    ------
    ValueError
        If the orders differ and a target field uses a non-identity
        transform or a non-default null order (``asc`` must be
        ``NULLS_FIRST`` and ``desc`` ``NULLS_LAST``), which
        :meth:`MigrationContext.replace_sort_order` cannot express, or
        a target field's source id is not in *schema*.
    """

    def _key(f: Any) -> tuple[Any, ...]:
        return (f.source_id, f.transform, f.direction, f.null_order)

    if len(current.fields) == len(target.fields) and all(
        _key(a) == _key(b) for a, b in zip(current.fields, target.fields, strict=True)
    ):
        return []

    sort_fields: list[tuple[str, str]] = []
    for f in target.fields:
        col = schema.find_column_name(f.source_id)
        if col is None:
            raise ValueError(f"sort field source id {f.source_id} is not in the schema.")
        ascending = f.direction == SortDirection.ASC
        if not isinstance(f.transform, IdentityTransform):
            raise ValueError(
                f"sort field {col!r} uses {f.transform}; autogenerate only renders "
                "identity sort fields. Write this sort order by hand."
            )
        default_nulls = NullOrder.NULLS_FIRST if ascending else NullOrder.NULLS_LAST
        if f.null_order != default_nulls:
            raise ValueError(
                f"sort field {col!r} uses {f.null_order} with {f.direction}; autogenerate "
                "only renders asc NULLS_FIRST and desc NULLS_LAST. Write this sort order by hand."
            )
        sort_fields.append((col, "asc" if ascending else "desc"))
    return [MigrationOp(kind="set_sort_order", args={"sort_fields": sort_fields})]


def properties_diff_to_ops(
    *,
    current: dict[str, str],
    target: dict[str, str],
) -> list[MigrationOp]:
    """
    Emit ``set_property`` and ``remove_property`` ops to reconcile the
    table-property dicts.

    Keys present in ``target`` but absent from ``current`` (or with a
    different value) become ``set_property`` ops. Keys present in
    ``current`` but absent from ``target`` become ``remove_property``
    ops; the old value is preserved in the args so the generated
    downgrade body can restore it.

    Parameters
    ----------
    current : dict[str, str]
        ``table.properties`` of the existing table.
    target : dict[str, str]
        Desired properties.

    Returns
    -------
    list[MigrationOp]
        ``remove_property`` ops (args ``{"key", "old_value"}``) first,
        then ``set_property`` ops (args ``{"key", "value",
        "old_value"}``), each group sorted by key.
    """
    ops: list[MigrationOp] = []

    # Removals first so the generated upgrade reads "remove old, set new".
    for key in sorted(current):
        if key not in target:
            ops.append(
                MigrationOp(
                    kind="remove_property",
                    args={"key": key, "old_value": current[key]},
                )
            )

    for key in sorted(target):
        new_value = target[key]
        if current.get(key) != new_value:
            ops.append(
                MigrationOp(
                    kind="set_property",
                    args={
                        "key": key,
                        "value": new_value,
                        "old_value": current.get(key),
                    },
                )
            )
    return ops


