_INDENT = " " * 8  # method body inside ``class Migration`` (two indent levels)


@dataclass(frozen=True)
class _Blocked:
    """One side of a rendered op that must not run as generated.

    ``reason`` explains why; ``lines`` are the generated calls, kept as
    comments in the output so the author can finish the method by hand.
    """

    reason: str
    lines: tuple[str, ...] = ()


# A rendered side of one op: runnable source lines, or a block.
_Side = list[str] | _Blocked

_ALLOWED_PROMOTIONS = (
    "allowed: int->long, float->double, decimal precision widening at the same scale"
)


def _render_add_column(op: MigrationOp) -> tuple[_Side, _Side]:
    name = op.args["name"]
    ice_type = op.args["iceberg_type"]
    doc = op.args.get("doc")
    doc_src = f", doc={doc!r}" if doc is not None else ""
    type_src = _iceberg_type_to_source(ice_type)
    downgrade: _Side = [f"ctx.delete_column(target_table, {name!r})"]
    if type_src is None:
        return (
            _Blocked(
                f"column {name!r}: type {ice_type} is not auto-renderable; "
                "write this step by hand",
                (f"ctx.enforce_column(target_table, {name!r}, ...{doc_src})",),
            ),
            downgrade,
        )
    return [f"ctx.enforce_column(target_table, {name!r}, {type_src}{doc_src})"], downgrade


def _render_rename_column(op: MigrationOp) -> tuple[_Side, _Side]:
    old, new = op.args["old_name"], op.args["new_name"]
    return (
        [f"ctx.enforce_rename(target_table, {old!r}, {new!r})"],
        [f"ctx.enforce_rename(target_table, {new!r}, {old!r})"],
    )


def _render_delete_column(op: MigrationOp) -> tuple[_Side, _Side]:
    name = op.args["name"]
    line = f"ctx.delete_column(target_table, {name!r})"
    downgrade = _Blocked(
        f"delete_column {name!r} cannot be reversed: re-adding creates a new, "
        "empty column (old data only via time travel)"
    )
    refs = op.args.get("referenced_by")
    if refs:
        return (
            _Blocked(
                f"column {name!r} is referenced by {', '.join(refs)}; remove those "
                "references first",
                (line,),
            ),
            downgrade,
        )
    return [line], downgrade


def _render_type_change(op: MigrationOp) -> tuple[_Side, _Side]:
    name = op.args["name"]
    old_type = op.args["old_iceberg_type"]
    new_type = op.args["new_iceberg_type"]
    new_src = _iceberg_type_to_source(new_type)
    downgrade = _Blocked(
        f"type change on {name!r} ({old_type} -> {new_type}) cannot be narrowed back; "
        "Iceberg only widens types"
    )
    line = f"ctx.enforce_column(target_table, {name!r}, {new_src or '...'})"
    if new_src is None or _iceberg_type_to_source(old_type) is None:
        return (
            _Blocked(
                f"column {name!r}: nested type change {old_type} -> {new_type} is not "
                "auto-renderable; write this step by hand",
                (line,),
            ),
            downgrade,
        )
    if not is_allowed_promotion(old_type, new_type):
        return (
            _Blocked(
                f"column {name!r}: {old_type} -> {new_type} is not an Iceberg type "
                f"promotion ({_ALLOWED_PROMOTIONS})",
                (line,),
            ),
            downgrade,
        )
    return [line], downgrade


def _render_add_partition_field(op: MigrationOp) -> tuple[_Side, _Side]:
    src_col = op.args["source_column"]
    transform = op.args["transform_source"]
    part_name = op.args["partition_name"]
    return (
        [
            "ctx.update_partition_spec(",
            "    target_table,",
            f"    add_fields=[({src_col!r}, {transform}, {part_name!r})],",
            ")",
        ],
        [
            "ctx.update_partition_spec(",
            "    target_table,",
            f"    remove_fields=[{part_name!r}],",
            ")",
        ],
    )


def _render_remove_partition_field(op: MigrationOp) -> tuple[_Side, _Side]:
    part_name = op.args["partition_name"]
    return (
        [
            "ctx.update_partition_spec(",
            "    target_table,",
            f"    remove_fields=[{part_name!r}],",
            ")",
        ],
        _Blocked(
            f"remove_partition_field {part_name!r} cannot be reversed: the original "
            "source column and transform are not recorded"
        ),
    )


def _render_set_sort_order(op: MigrationOp) -> tuple[_Side, _Side]:
    fields_repr = ", ".join(repr((col, direction)) for col, direction in op.args["sort_fields"])
    return (
        [
            "ctx.replace_sort_order(",
            "    target_table,",
            f"    sort_fields=[{fields_repr}],",
            ")",
        ],
        _Blocked("set_sort_order cannot be reversed: the previous sort order is not recorded"),
    )


def _render_set_property(op: MigrationOp) -> tuple[_Side, _Side]:
    key = op.args["key"]
    value = op.args["value"]
    old_value = op.args.get("old_value")
    upgrade = [f"ctx.set_table_properties(target_table, {{{key!r}: {value!r}}})"]
    if old_value is None:
        downgrade = [f"ctx.unset_table_properties(target_table, [{key!r}])"]
    else:
        downgrade = [f"ctx.set_table_properties(target_table, {{{key!r}: {old_value!r}}})"]
    return upgrade, downgrade


def _render_remove_property(op: MigrationOp) -> tuple[_Side, _Side]:
    key = op.args["key"]
    old_value = op.args.get("old_value")
    upgrade: _Side = [f"ctx.unset_table_properties(target_table, [{key!r}])"]
    if old_value is None:
        return upgrade, _Blocked(
            f"remove_property {key!r} cannot be reversed: the old value was not recorded"
        )
    return upgrade, [f"ctx.set_table_properties(target_table, {{{key!r}: {old_value!r}}})"]


_RENDERERS: dict[str, Callable[[MigrationOp], tuple[_Side, _Side]]] = {
    "add_column": _render_add_column,
    "rename_column": _render_rename_column,
    "delete_column": _render_delete_column,
    "type_change": _render_type_change,
    "add_partition_field": _render_add_partition_field,
    "remove_partition_field": _render_remove_partition_field,
    "set_sort_order": _render_set_sort_order,
    "set_property": _render_set_property,
    "remove_property": _render_remove_property,
}


def _render_pairs(ops: list[MigrationOp]) -> list[tuple[_Side, _Side]]:
    """Run each op's renderer, in op order."""
    pairs: list[tuple[_Side, _Side]] = []
    for op in ops:
        renderer = _RENDERERS.get(op.kind)
        if renderer is None:
            raise ValueError(f"Unknown MigrationOp kind: {op.kind!r}")
        pairs.append(renderer(op))
    return pairs


def _blocking_reasons(ops: list[MigrationOp]) -> tuple[list[str], list[str]]:
    """Reasons the rendered ``upgrade`` / ``downgrade`` will raise.

    Returns
    -------
    (upgrade_reasons, downgrade_reasons) : tuple of list[str]
        Empty lists mean that method runs as generated.
    """
    pairs = _render_pairs(ops)
    up = [side.reason for side, _ in pairs if isinstance(side, _Blocked)]
    down = [side.reason for _, side in reversed(pairs) if isinstance(side, _Blocked)]
    return up, down


def _comment(text: str) -> str:
    """Render *text* as a single comment line (no line breaks can escape)."""
    return "# " + "".join(ch if ch.isprintable() else " " for ch in text)


def _assemble(method: str, fragments: list[_Side], target_repr: str) -> list[str]:
    """Build one method body from rendered fragments.

    Without blocks the fragments are emitted in order. With any block
    the body raises :class:`NotImplementedError` straight after
    ``target_table`` is set - no ctx call precedes it - and every
    fragment follows as comments, in order.
    """
    lines = [f"target_table = {target_repr}", ""]
    reasons = [frag.reason for frag in fragments if isinstance(frag, _Blocked)]
    if not reasons:
        for frag in fragments:
            assert not isinstance(frag, _Blocked)
            lines.extend(frag)
        return lines

    message = (
        f"Autogenerated {method}() must be completed by hand before it can run; "
        "no step has been applied. " + " ".join(f"[{r}]" for r in reasons)
    )
    lines.append(f"raise NotImplementedError({message!r})")
    lines.append("")
    lines.append("# Generated steps, in order, kept for manual completion:")
    for frag in fragments:
        if isinstance(frag, _Blocked):
            if frag.lines:
                lines.extend(_comment(line) for line in frag.lines)
            else:
                lines.append(_comment(f"(irreversible) {frag.reason}"))
        else:
            lines.extend(_comment(line) for line in frag)
    return lines


def render_migration_body(
    ops: list[MigrationOp],
    *,
    target_table: str,
) -> tuple[str, str]:
    """
    Translate a list of :class:`MigrationOp` into ``upgrade`` and
    ``downgrade`` method body source strings.

    Parameters
    ----------
    ops : list[MigrationOp]
        Output of :func:`schema_diff_to_ops` and friends.
    target_table : str
        Table identifier used in the generated calls. Prefer a bare
        name (``"orders"``): the migration context qualifies it with
        the namespace the migration runs against, so one file serves
        every namespace. A dotted name (``"sales.orders"``) pins the
        namespace - the migration always modifies that table.

    Returns
    -------
    (upgrade_body, downgrade_body) : tuple of str
        Each is a ``\\n``-joined block of indented Python source ready
        to drop into a :class:`~iceberg_ops.migration.BaseMigration`
        method.

    Raises
    ------
    ValueError
        If an op has an unknown ``kind``.

    Notes
    -----
    The downgrade order is the reverse of upgrade - matches the
    classic schema-migration convention. When any step of a method
    cannot run as generated (an incompatible or nested type change, or
    dropping a column the table layout references, on upgrade; a column
    drop, type widening, partition-field removal,
    sort-order replacement or property removal without a recorded old
    value on downgrade), that method raises
    :class:`NotImplementedError` before any step runs and keeps every
    generated call as a comment.
    """
    upgrade_lines: list[str]
    downgrade_lines: list[str]
    if not ops:
        upgrade_lines = ["pass  # autogenerated: no schema differences detected"]
        downgrade_lines = ["pass  # autogenerated: nothing to revert"]
        return _indent_block(upgrade_lines), _indent_block(downgrade_lines)

    target_repr = repr(target_table)
    pairs = _render_pairs(ops)
    upgrade_lines = _assemble("upgrade", [up for up, _ in pairs], target_repr)
    # Downgrade is the reverse order of ops.
    downgrade_lines = _assemble("downgrade", [down for _, down in reversed(pairs)], target_repr)
    return _indent_block(upgrade_lines), _indent_block(downgrade_lines)


def _indent_block(lines: list[str]) -> str:
    """Prefix each line with the migration-method indent."""
    return "\n".join(_INDENT + line if line else "" for line in lines)


