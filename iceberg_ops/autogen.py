# All op kinds emitted by the diff functions and consumed by the renderer.
MigrationOpKind = Literal[
    "add_column",
    "rename_column",
    "delete_column",
    "type_change",
    "add_partition_field",
    "remove_partition_field",
    "set_sort_order",
    "set_property",
    "remove_property",
]


@dataclass
class MigrationOp:
    """A single migration operation that the autogen renderer will emit.

    Attributes
    ----------
    kind : str
        One of the supported op kinds. See :data:`MigrationOpKind`.
    args : dict
        Op-specific arguments. The schema is documented per-kind in
        the diff functions below; the renderer reads these args to
        generate the matching Python source.
    """

    kind: MigrationOpKind
    args: dict[str, Any] = field(default_factory=dict)


