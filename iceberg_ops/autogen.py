def _iceberg_type_to_source(t: ice_types.IcebergType) -> str | None:
    """Render an Iceberg type as its Python source form (qualified by
    the ``ice_types.`` alias the renderer always imports).

    Examples
    --------
    >>> _iceberg_type_to_source(ice_types.LongType())
    'ice_types.LongType()'
    >>> _iceberg_type_to_source(ice_types.DecimalType(10, 2))
    'ice_types.DecimalType(precision=10, scale=2)'

    Returns ``None`` for nested types
    (:class:`~pyiceberg.types.ListType` / :class:`~pyiceberg.types.MapType` /
    :class:`~pyiceberg.types.StructType`) and for any type whose
    ``repr`` is not a plain constructor call with literal arguments; the
    renderer blocks such steps instead of emitting them.
    """
    if not isinstance(t, ice_types.PrimitiveType):
        return None
    src = repr(t)
    try:
        node = ast.parse(src, mode="eval").body
    except SyntaxError:
        return None
    if not (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and getattr(ice_types, node.func.id, None) is type(t)
        and all(isinstance(arg, ast.Constant) for arg in node.args)
        and all(isinstance(kw.value, ast.Constant) for kw in node.keywords)
    ):
        return None
    return f"ice_types.{src}"


def _align_target_to_current(
    target_fields: list[tuple[str, ice_types.IcebergType, str | None, bool]],
    current: IcebergSchema,
    rename_hints: dict[str, str],
) -> IcebergSchema:
    """Build an :class:`IcebergSchema` from raw target fields, reusing
    ``current`` field-IDs by name (with rename-hint indirection).

    Each entry of ``target_fields`` is ``(name, type, doc, required)``.
    The aligned schema has the same column order as ``target_fields``;
    field-IDs are taken from ``current`` for matching names, fresh IDs
    are issued for genuinely new columns.

    Rename mechanics: a hint ``{"old_name": "new_name"}`` makes the
    target's ``new_name`` field carry ``current["old_name"].field_id``,
    so :func:`~iceberg_ops.core.schema.diff_schemas` recognises the
    pair as a rename rather than drop+add.
    """
    current_by_name = {f.name: f for f in current.fields}
    rev_hints = {new: old for old, new in rename_hints.items()}
    next_id = max((f.field_id for f in current.fields), default=0) + 1

    nested: list[ice_types.NestedField] = []
    for name, ice_type, doc, required in target_fields:
        if name in rev_hints and rev_hints[name] in current_by_name:
            fid = current_by_name[rev_hints[name]].field_id
        elif name in current_by_name:
            fid = current_by_name[name].field_id
        else:
            fid = next_id
            next_id += 1
        nested.append(
            ice_types.NestedField(
                field_id=fid,
                name=name,
                field_type=ice_type,
                required=required,
                doc=doc,
            )
        )
    return IcebergSchema(*nested)


def _arrow_field_to_iceberg_type(
    f: pa.Field,
    current: IcebergSchema,
    rename_hints: dict[str, str],
) -> ice_types.IcebergType:
    """Map one target :class:`pa.Field` to its Iceberg type.

    Primitive fields go through
    :func:`iceberg_ops.core.types.arrow_type_to_iceberg`. A nested field
    (list / struct / map) whose column (or rename-hint source) already
    exists as a nested column reuses the current type: it is treated as
    unchanged and a warning says it was not compared. A nested field
    for a new column, or one replacing a primitive column, raises.
    """
    if not pa.types.is_nested(f.type):
        return arrow_type_to_iceberg(f.type)
    source = {new: old for old, new in rename_hints.items()}.get(f.name, f.name)
    current_by_name = {cf.name: cf for cf in current.fields}
    existing = current_by_name.get(source)
    if existing is not None and not isinstance(existing.field_type, ice_types.PrimitiveType):
        logger.warning(
            "Nested column %r in the pa.Schema target was not compared; "
            "it is treated as unchanged.",
            f.name,
        )
        return existing.field_type
    if existing is not None:
        raise ValueError(
            f"Column {f.name!r} changes to a nested type in the pa.Schema target; "
            "autogenerate cannot render this, use a hand-written migration."
        )
    raise ValueError(
        f"Nested column {f.name!r} in a pa.Schema target cannot be added by "
        "autogenerate; use a hand-written migration or an IcebergSchema target."
    )


def _normalise_target(
    target: pa.Schema | IcebergSchema | SchemaContract,
    current: IcebergSchema,
    rename_hints: dict[str, str],
) -> IcebergSchema:
    """Convert any supported ``target`` representation into an
    ID-aligned :class:`IcebergSchema` ready for :func:`diff_schemas`.

    - :class:`IcebergSchema`: passed through (caller is responsible for IDs).
    - :class:`pa.Schema`: each field's type is mapped via
      :func:`_arrow_field_to_iceberg_type`; ``required`` is the inverse
      of Arrow's ``nullable`` flag; ``doc`` is taken from Arrow's field
      metadata under the ``b"doc"`` key when present.
    - :class:`SchemaContract`: ``ColumnSpec`` already carries
      everything; we just translate to the tuple form.
    """
    if isinstance(target, IcebergSchema):
        return target

    fields: list[tuple[str, ice_types.IcebergType, str | None, bool]] = []
    if isinstance(target, pa.Schema):
        for f in target:
            doc = None
            if f.metadata and b"doc" in f.metadata:
                doc = f.metadata[b"doc"].decode("utf-8")
            fields.append(
                (
                    f.name,
                    _arrow_field_to_iceberg_type(f, current, rename_hints),
                    doc,
                    not f.nullable,
                )
            )
    elif isinstance(target, SchemaContract):
        for col in target.columns:
            fields.append((col.name, col.type, col.doc, col.required))
    else:
        raise TypeError(
            f"Unsupported target type {type(target).__name__}: "
            "expected pa.Schema, IcebergSchema, or SchemaContract."
        )

    return _align_target_to_current(fields, current, rename_hints)


def _target_names(target: pa.Schema | IcebergSchema | SchemaContract) -> list[str]:
    """Top-level column names of any supported target, in order."""
    if isinstance(target, IcebergSchema):
        return [f.name for f in target.fields]
    if isinstance(target, pa.Schema):
        return list(target.names)
    if isinstance(target, SchemaContract):
        return [c.name for c in target.columns]
    raise TypeError(
        f"Unsupported target type {type(target).__name__}: "
        "expected pa.Schema, IcebergSchema, or SchemaContract."
    )


def _validate_rename_hints(
    hints: dict[str, str],
    current_names: Iterable[str],
    target_names: Iterable[str],
) -> None:
    """Reject rename hints that would silently lose or corrupt columns.

    Raises
    ------
    ValueError
        When a hint's old name is not a current column, its new name is
        not a target column, the old name is still in the target, the
        new name already exists in the current table (swaps and chained
        renames need two migrations), or two hints share a new name.
    """
    current_set, target_set = set(current_names), set(target_names)
    claimed: dict[str, str] = {}
    for old, new in hints.items():
        label = f"rename hint {old!r} -> {new!r}"
        if old not in current_set:
            raise ValueError(f"{label}: {old!r} is not a column of the current table.")
        if new not in target_set:
            raise ValueError(f"{label}: {new!r} is not a column of the target schema.")
        if old in target_set:
            raise ValueError(
                f"{label}: {old!r} is still in the target schema, so it is not being renamed."
            )
        if new in current_set:
            raise ValueError(
                f"{label}: {new!r} already exists in the current table; swaps and "
                "chained renames have to be done in two migrations."
            )
        if new in claimed:
            raise ValueError(
                f"{label}: {new!r} is also the target of the hint for {claimed[new]!r}."
            )
        claimed[new] = old


def _drops_unlisted(target: pa.Schema | IcebergSchema | SchemaContract) -> bool:
    """Whether columns missing from *target* should be dropped."""
    return not isinstance(target, SchemaContract) or target.strict


def _unlisted_columns_kept(
    current: IcebergSchema,
    target: pa.Schema | IcebergSchema | SchemaContract,
    rename_hints: dict[str, str] | None = None,
) -> list[str]:
    """Current columns a non-strict :class:`SchemaContract` target keeps.

    Returns the current column names that are neither listed in the
    contract nor the source of a rename hint; ``[]`` for any other
    target (those drop unlisted columns).
    """
    if _drops_unlisted(target):
        return []
    listed = set(_target_names(target)) | set(rename_hints or {})
    return [f.name for f in current.fields if f.name not in listed]


def _uncompared_nested_columns(
    current: IcebergSchema,
    target: pa.Schema | IcebergSchema | SchemaContract,
    rename_hints: dict[str, str] | None = None,
) -> list[str]:
    """Nested columns of a :class:`pa.Schema` target that are not compared.

    A nested (struct / list / map) target field whose column, or
    rename-hint source, already exists as a nested column is treated
    as unchanged (see :func:`_arrow_field_to_iceberg_type`). Returns the
    target names of those columns; ``[]`` for any other target type.
    """
    if not isinstance(target, pa.Schema):
        return []
    sources = {new: old for old, new in (rename_hints or {}).items()}
    current_by_name = {f.name: f for f in current.fields}
    skipped: list[str] = []
    for f in target:
        if not pa.types.is_nested(f.type):
            continue
        existing = current_by_name.get(sources.get(f.name, f.name))
        if existing is not None and not isinstance(existing.field_type, ice_types.PrimitiveType):
            skipped.append(f.name)
    return skipped


def _ignored_attribute_changes(
    current: IcebergSchema,
    target: pa.Schema | IcebergSchema | SchemaContract,
    rename_hints: dict[str, str] | None = None,
) -> list[str]:
    """Describe nullability / doc differences autogenerate does not emit.

    Compares ``required`` and ``doc`` for every column present in both
    schemas (matched by field id, so renames count), and flags new
    columns the target marks required (they are added as optional).
    A target doc of ``None`` means "unspecified" and is not reported.

    Returns
    -------
    list[str]
        One entry per affected column, e.g.
        ``"id (optional -> required)"``.
    """
    hints = dict(rename_hints or {})
    target_iceberg = _normalise_target(target, current, hints)
    current_by_id = {f.field_id: f for f in current.fields}
    notes: list[str] = []
    for tf in target_iceberg.fields:
        cf = current_by_id.get(tf.field_id)
        if cf is None:
            if tf.required:
                notes.append(f"{tf.name} (new column added as optional, target is required)")
            continue
        changes: list[str] = []
        if cf.required != tf.required:
            old_req = "required" if cf.required else "optional"
            new_req = "required" if tf.required else "optional"
            changes.append(f"{old_req} -> {new_req}")
        if tf.doc is not None and tf.doc != cf.doc:
            changes.append("doc differs")
        if changes:
            notes.append(f"{tf.name} ({', '.join(changes)})")
    return notes


def _required_format_version(t: ice_types.IcebergType) -> int:
    """Lowest table format version that can hold *t* (nested fields included)."""
    from pyiceberg.schema import index_by_id

    versions = [int(t.minimum_format_version())]
    if not t.is_primitive:
        versions.extend(
            int(f.field_type.minimum_format_version()) for f in index_by_id(t).values()
        )
    return max(versions)


def _layout_references(
    field: ice_types.NestedField,
    current: IcebergSchema,
    spec: PartitionSpec | None,
    sort_order: SortOrder | None,
) -> list[str]:
    """Describe what in the table layout references *field* or its children.

    Checks the identifier fields of ``current`` and, when given, the
    non-void fields of ``spec`` and the fields of ``sort_order`` -
    the references PyIceberg refuses to leave dangling when a column is
    deleted.
    """
    from pyiceberg.schema import index_by_id

    ids = {field.field_id, *index_by_id(field.field_type)}
    refs: list[str] = []
    if spec is not None:
        refs.extend(
            f"partition field {pf.name!r}"
            for pf in spec.fields
            if pf.source_id in ids and not isinstance(pf.transform, VoidTransform)
        )
    if sort_order is not None and any(sf.source_id in ids for sf in sort_order.fields):
        refs.append("the sort order")
    if ids & set(current.identifier_field_ids):
        refs.append("the identifier fields")
    return refs


def _check_op_names(ops: list[MigrationOp]) -> None:
    """Refuse ops on column names that contain a dot.

    Raises
    ------
    ValueError
        If any op's ``name`` / ``old_name`` / ``new_name`` contains
        ``"."``.
    """
    dotted = sorted(
        {
            str(op.args[key])
            for op in ops
            for key in ("name", "old_name", "new_name")
            if "." in str(op.args.get(key) or "")
        }
    )
    if dotted:
        raise ValueError(
            f"Column name(s) {', '.join(repr(n) for n in dotted)} contain '.', which "
            "MigrationContext helpers read as a nested struct path; write this step "
            "by hand."
        )


def _check_format_version(ops: list[MigrationOp], format_version: int) -> None:
    """Refuse added or changed column types the table's format version cannot hold.

    Raises
    ------
    ValueError
        If an ``add_column`` / ``type_change`` type needs a newer table
        format version than *format_version*.
    """
    for op in ops:
        key = {"add_column": "iceberg_type", "type_change": "new_iceberg_type"}.get(op.kind)
        if key is None:
            continue
        ice_type = op.args[key]
        needed = _required_format_version(ice_type)
        if needed > format_version:
            raise ValueError(
                f"column {op.args['name']!r}: {ice_type} needs table format version "
                f"{needed}; the table is version {format_version}."
            )


def schema_diff_to_ops(
    *,
    current: IcebergSchema,
    target: pa.Schema | IcebergSchema | SchemaContract,
    rename_hints: dict[str, str] | None = None,
    format_version: int | None = None,
    spec: PartitionSpec | None = None,
    sort_order: SortOrder | None = None,
) -> list[MigrationOp]:
    """
    Compute the list of :class:`MigrationOp` that turns ``current`` into
    ``target`` for column schema only (add / rename / delete /
    type_change).

    Uses :func:`~iceberg_ops.core.schema.diff_schemas` under the hood.
    Renames are disambiguated by ``rename_hints`` (a mapping
    ``{old_name: new_name}``); when no hint covers a pair, a column
    rename is emitted as drop + add.

    Parameters
    ----------
    current : IcebergSchema
        Schema of the existing table - must carry stable field-IDs from
        a real Iceberg table (e.g. ``table.schema()``).
    target : pa.Schema | IcebergSchema | SchemaContract
        Desired schema. :class:`IcebergSchema` is passed through;
        :class:`pa.Schema` and :class:`SchemaContract` are normalised by
        reusing ``current`` field-IDs for fields with the same name (or
        via rename hints). Columns of ``current`` missing from the
        target are dropped, except for a non-strict
        :class:`SchemaContract` (``strict=False``, the default), which
        only reconciles the columns it lists and keeps the rest.
        Nested columns of a :class:`pa.Schema` target are not compared
        when they already exist, and cannot be added.
    rename_hints : dict[str, str], optional
        Map of ``old_column_name`` -> ``new_column_name``. Each entry
        causes a single ``rename_column`` op instead of drop + add.
        Not accepted with an :class:`IcebergSchema` target, whose field
        IDs already identify renames.
    format_version : int, optional
        The table's format version (``table.format_version``). When
        given, an added or changed column whose type needs a newer
        version (``timestamp_ns``, ``timestamptz_ns``, ``unknown``,
        ``geometry`` and ``geography`` need version 3) raises
        ``ValueError``. ``None`` (default) skips the check.
    spec : PartitionSpec, optional
        The partition spec in effect when the deletes run (normally
        ``table.spec()``). Deleting a column one of its non-void fields
        is sourced from is rendered as an ``upgrade`` that raises.
    sort_order : SortOrder, optional
        The sort order in effect when the deletes run (normally
        ``table.sort_order()``); deleting a column it sorts by is
        rendered as an ``upgrade`` that raises. The identifier fields
        of ``current`` are always checked the same way.

    Returns
    -------
    list[MigrationOp]
        Ordered list of ops. Order: removed -> renamed -> type-changed
        -> added; this keeps downstream renders deterministic.

    Raises
    ------
    ValueError
        If a rename hint is inconsistent with the two schemas (unknown
        old or new name, old name kept, new name already present, two
        hints sharing a new name), if hints are combined with an
        :class:`IcebergSchema` target, if the target repeats a column
        name, if a target column type cannot be mapped, if an op names
        a column containing ``"."`` (the ``MigrationContext`` helpers
        read a dot as a nested struct path), or if *format_version* is
        given and an added or changed type needs a newer one.
    TypeError
        If ``target`` is not one of the supported types.

    Notes
    -----
    Op kinds emitted:

    - ``add_column`` - args ``{"name", "iceberg_type", "doc"}``
    - ``rename_column`` - args ``{"old_name", "new_name"}``
    - ``delete_column`` - args ``{"name"}``, plus ``"referenced_by"``
      (list of str) when the identifier fields, *spec* or *sort_order*
      reference the column; the renderer then blocks the ``upgrade``.
    - ``type_change`` - args ``{"name", "old_iceberg_type", "new_iceberg_type"}``

    The ``iceberg_type`` values are :class:`pyiceberg.types.IcebergType`
    instances; the renderer converts them to source code. A
    ``type_change`` that is not an Iceberg type promotion is still
    emitted so the diff stays visible; the renderer turns it into an
    ``upgrade`` that raises.

    Nullability and doc changes on existing columns are not emitted
    yet (PyIceberg supports them via ``UpdateSchema.make_column_optional``
    and ``update_column(doc=...)``). New columns are added as optional,
    with the target doc when one is set.
    """
    hints = dict(rename_hints or {})
    target_names = _target_names(target)
    duplicates = sorted({n for n in target_names if target_names.count(n) > 1})
    if duplicates:
        raise ValueError(f"Target schema repeats column name(s): {', '.join(duplicates)}.")
    if hints:
        if isinstance(target, IcebergSchema):
            raise ValueError(
                "rename_hints cannot be used with an IcebergSchema target: "
                "its field IDs already identify renames."
            )
        _validate_rename_hints(hints, (f.name for f in current.fields), target_names)

    target_iceberg = _normalise_target(target, current, hints)
    diff = diff_schemas(current, target_iceberg)

    target_by_id = {f.field_id: f for f in target_iceberg.fields}
    current_by_id = {f.field_id: f for f in current.fields}

    ops: list[MigrationOp] = []

    # Removed columns first - emit before adds so generated migrations
    # don't briefly carry both old and new versions of a soon-to-rename
    # column when no rename hint covers it.
    if _drops_unlisted(target):
        for removed in diff.removed:
            assert removed.field_id is not None
            args: dict[str, Any] = {"name": removed.name}
            refs = _layout_references(current_by_id[removed.field_id], current, spec, sort_order)
            if refs:
                args["referenced_by"] = refs
            ops.append(MigrationOp(kind="delete_column", args=args))
    elif diff.removed:
        logger.info(
            "Keeping %d column(s) not listed in the non-strict contract: %s",
            len(diff.removed),
            ", ".join(r.name for r in diff.removed),
        )

    # Renames (changed entries with change_type == "renamed").
    for changed in diff.changed:
        if changed.change_type == "renamed":
            ops.append(
                MigrationOp(
                    kind="rename_column",
                    args={
                        "old_name": changed.old_name,
                        "new_name": changed.name,
                    },
                )
            )

    # Type changes - keep the actual IcebergType instances so the
    # renderer can check the promotion rule and nested types.
    for changed in diff.changed:
        if changed.change_type == "type_changed":
            # FieldChange.field_id is typed Optional[int]; the
            # diff_schemas path only emits "type_changed" entries for
            # fields present in both schemas, so the id is guaranteed
            # populated here.
            assert changed.field_id is not None
            old_type = current_by_id[changed.field_id].field_type
            new_type = target_by_id[changed.field_id].field_type
            ops.append(
                MigrationOp(
                    kind="type_change",
                    args={
                        "name": changed.name,
                        "old_iceberg_type": old_type,
                        "new_iceberg_type": new_type,
                    },
                )
            )

    # Adds last - for type_change semantics described above.
    for added in diff.added:
        assert added.field_id is not None
        target_field = target_by_id[added.field_id]
        ops.append(
            MigrationOp(
                kind="add_column",
                args={
                    "name": added.name,
                    "iceberg_type": target_field.field_type,
                    "doc": target_field.doc,
                },
            )
        )

    _check_op_names(ops)
    if format_version is not None:
        _check_format_version(ops, format_version)
    return ops


