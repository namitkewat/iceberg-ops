"""
iceberg_ops.autogen
===================
Autogenerate migration files from a schema diff.

This module powers ``iceberg-ops revision --autogenerate``: it compares an
existing Iceberg table against a target schema (``pa.Schema``,
:class:`~iceberg_ops.core.schema.SchemaContract`, or
:class:`pyiceberg.schema.Schema`) and produces a list of
:class:`MigrationOp`, which the renderer then turns into runnable
migration source code.

Public API
----------
:class:`MigrationOp`
    Dataclass describing one op (kind + args).

:func:`schema_diff_to_ops(*, current, target, rename_hints=None, format_version=None, spec=None, sort_order=None)`
    Compute the ops that turn ``current`` into ``target`` for column
    schema (add / rename / delete / type_change).

:func:`spec_diff_to_ops(*, current, target, schema)`
    Compute the ops that turn ``current`` partition spec into
    ``target``.

:func:`sort_order_diff_to_ops(*, current, target, schema)`
    Emit one ``set_sort_order`` op when the orders differ.

:func:`properties_diff_to_ops(*, current, target)`
    Emit ``set_property`` / ``remove_property`` ops.

:func:`render_migration_body(ops, *, target_table)`
    Translate a ``list[MigrationOp]`` into ``(upgrade_body,
    downgrade_body)`` Python source strings ready to drop into a
    :class:`~iceberg_ops.migration.BaseMigration` skeleton.

:func:`render_migration_file(*, version, description, ops, target_table)`
    Top-level helper that produces the full migration file source.

:func:`write_autogenerated_revision(*, version, description, ops, target_table, out_path, overwrite=False)`
    Render and write the file to disk (UTF-8, LF line endings). Refuses
    to replace an existing file unless ``overwrite=True``.

Scope
-----
- Every name, value and description rendered into a generated file is
  written as a Python literal (``repr``), so a generated file always
  compiles and cannot run code smuggled in through a column name or a
  ``-m`` message.
- Schema column ops handle primitive Iceberg types. Type changes are
  emitted only for Iceberg type promotions (``int -> long``,
  ``float -> double``, decimal precision widening at the same scale).
- Column names containing a dot are refused: the ``MigrationContext``
  helpers read a dot as a nested struct path.
- Steps that cannot run as generated (incompatible type changes, nested
  types, dropping a column the partition spec, sort order or identifier
  fields reference) or cannot be reversed (column drops, type widening,
  partition-field removal, sort-order replacement, property removal with
  an unknown old value) make the affected ``upgrade`` / ``downgrade``
  raise :class:`NotImplementedError` before any step runs. The generated
  calls are kept as comments so the author can finish the method by
  hand.
- Partition specs and sort orders are diffed for programmatic use; the
  CLI front-end (``revision --autogenerate``) is schema-only.
- Nullability and doc changes on existing columns are not emitted yet.
"""

